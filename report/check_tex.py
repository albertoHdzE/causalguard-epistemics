#!/usr/bin/env python3
"""Keep the "no hand-typed number" guarantee when report/report.tex is edited by hand (iteration 13, D133).

report.md is generated by fill.py, so every number in it comes from the analysis outputs.  report.tex is generated
from report.md by pandoc and may then be edited by hand.  This check fails unless the multiset of numeric tokens in
the body of report.tex (from the template's "--- body" marker to \\end{document}, LaTeX markup removed and escapes
undone) equals the multiset of numeric tokens in the body of report.md (front matter, comments, link targets and
image attributes removed).  Prose may be reworded freely; a number may not be added, dropped or changed.

Usage: python report/check_tex.py [--md report/report.md] [--tex report/report.tex]
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
MARKER = "% --- body (report/check_tex.py"
TOKEN = re.compile(r"(?<![\w.])\d+(?:[.:,]\d+)*")
URL = re.compile(r"https?://[^\s}{)\]]+")


def _strip_list_markers(s: str) -> str:
    """Drop "N. " at the start of a list item: after a blank line or inside a list (pandoc needs one of the two;
    a wrapped prose line that happens to begin with a number stays prose)."""
    out, in_list, prev_blank = [], False, True
    for line in s.split("\n"):
        item = re.match(r"\s*\d+\.\s", line)
        if item and (prev_blank or in_list):
            line, in_list = " " + line[item.end():], True
        elif not line.strip():
            pass
        elif not line[:1].isspace():
            in_list = False                                             # an unindented line ends the list
        prev_blank = not line.strip()
        out.append(line)
    return "\n".join(out)


def md_body(md: str) -> str:
    s = re.sub(r"\A---\n.*?\n---\n", "", md, flags=re.S)               # front matter (title block)
    s = re.sub(r"<!--.*?-->", " ", s, flags=re.S)                       # comments
    s = re.sub(r"\]\([^)]*\)", "]", s)                                  # link and image targets
    s = re.sub(r"\{(?:width|height)=[^}]*\}", " ", s)                   # image attributes
    s = re.sub(r"^:::.*$", " ", s, flags=re.M)                          # fenced Div markers
    s = _strip_list_markers(s)                                          # ordered-list markers (\item in LaTeX)
    s = s.replace("\\(", "(")                                           # markdown escapes
    return URL.sub(" ", s)


# LaTeX constructs whose arguments are layout, targets or labels, never prose (pandoc's output; see report.tex).
_DROP = [
    r"\\begin\{longtable\}\[\]\{@\{\}.*?@\{\}\}",                       # column specification (widths)
    r"\\(?:label|hypertarget|ref|pageref|url|includegraphics(?:\[[^\]]*\])?|def\\LTcaptype)\{[^{}]*\}",
    r"\\href\{[^{}]*\}",                                                # link target (the text is kept)
    r"\\begin\{minipage\}\[[^\]]*\]\{[^{}]*\}",
    r"\\(?:real|arraybackslash)\{[^{}]*\}",
    r"\\(?:setlength|addtolength)\{[^{}]*\}\{[^{}]*\}",
    r"\(\\(?:linewidth|columnwidth|textwidth)[^()]*\)",                 # (\linewidth - 6\tabcolsep)
    r"\\multicolumn\{\d+\}\{[^{}]*\}",
    r"\\(?:vspace|hspace)\*?\{[^{}]*\}",
    r"\\setcounter\{[^{}]*\}\{[^{}]*\}",                                # list start (ordered lists)
]
_ESC = [("\\textbar{}", "|"), ("\\textbar", "|"), ("\\textless{}", "<"), ("\\textgreater{}", ">"),
        ("\\textasciitilde{}", "~"), ("\\textbackslash{}", "\\"), ("\\textasciicircum{}", "^"), ("{[}", "["),
        ("{]}", "]"), ("\\_", "_"), ("\\%", "%"), ("\\&", "&"), ("\\#", "#"), ("\\$", "$"), ("\\{", "{"),
        ("\\}", "}"), ("\\ldots{}", "…"), ("\\allowbreak{}", ""), ("\\allowbreak", ""), ("\\,", " ")]


def tex_body(tex: str) -> str:
    if MARKER not in tex:
        raise SystemExit(f"check_tex: the body marker line ({MARKER} ...) is missing from report.tex")
    s = tex.split(MARKER, 1)[1].split("\n", 1)[1]
    s = s.split("\\end{document}", 1)[0]
    s = re.sub(r"(?<!\\)%.*$", " ", s, flags=re.M)                     # comments
    s = URL.sub(" ", s)
    for pat in _DROP:
        s = re.sub(pat, " ", s, flags=re.S)
    for a, b in _ESC:
        s = s.replace(a, b)
    s = re.sub(r"\\[A-Za-z]+\*?", " ", s)                              # remaining control words (text kept)
    return s


def tokens(text: str) -> Counter:
    return Counter(t.replace(",", "") for t in TOKEN.findall(text))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default=str(HERE / "report.md"))
    ap.add_argument("--tex", default=str(HERE / "report.tex"))
    a = ap.parse_args(argv)
    m = tokens(md_body(Path(a.md).read_text()))
    t = tokens(tex_body(Path(a.tex).read_text()))
    if m == t:
        print(f"check_tex: OK ({sum(t.values())} numeric tokens, {len(t)} distinct, identical in report.tex and report.md)")
        return 0
    for tok in sorted(set(m) | set(t)):
        if m[tok] != t[tok]:
            print(f"check_tex: {tok!r}: report.md {m[tok]}, report.tex {t[tok]}", file=sys.stderr)
    print("check_tex: FAILED: the numbers in report.tex differ from those generated into report.md "
          "(edit the prose, not the numbers; numbers change only through report.src.md and fill.py)", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
