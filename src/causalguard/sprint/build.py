"""R7 sprint build steps (no model calls): manifests, the surface rule fit, and the engine-agreement check.

  python -m causalguard sprint-build manifests            -> artifacts/sprint_{smoke,pilot,main}_manifest.json
  python -m causalguard sprint-build surface              -> artifacts/sprint_surface_rule.json (train split only)
  python -m causalguard sprint-build engines --split S    -> exact engine agreement on every claim of a split
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from . import population as P
from . import surface

ART = P.REPO / "artifacts"


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=1, sort_keys=True) + "\n")


def manifests(splits=("smoke", "pilot", "main")) -> dict:
    out = {}
    for s in splits:
        m = P.manifest(s)
        write_json(ART / f"sprint_{s}_manifest.json", m)
        out[s] = m
        cond = Counter(x["condition"] for x in m["items"])
        print(f"manifest {s}: {m['n_worlds']} worlds, conditions {dict(sorted(cond.items()))}")
    return out


def engines(split: str, quiet: bool = True) -> dict:
    """Every claim of every world of the split through ``Evaluator.reference`` (explicit = D counts and the SAT
    verdict); an exception on any claim is a failed item.  Prints the denominator."""
    keys = P.world_keys(split)
    if not keys:
        raise SystemExit("engines: empty split")
    ok = fail = claims = 0
    st = Counter()
    failures = []
    for k in keys:
        try:
            ref = P.reference(P.evaluator(k))
            ok += 1
            claims += len(ref)
            st.update(r["status"] for r in ref.values())
        except AssertionError as e:
            fail += 1
            failures.append({"wkey": k.wkey, "error": str(e)[:200]})
    res = {"split": split, "worlds": len(keys), "worlds_agree": ok, "worlds_fail": fail, "claims_agree": claims,
           "status_counts": dict(st), "failures": failures}
    print(f"engines {split}: {ok}/{len(keys)} worlds agree ({claims} claims); status {dict(st)}")
    return res


def fit_surface() -> dict:
    keys = P.world_keys("train")
    items = []
    for k in keys:
        ev = P.evaluator(k)
        items.append((ev.public(), P.reference(ev, crosscheck_sat=False)))
    rule = surface.fit(items)
    write_json(ART / "sprint_surface_rule.json", rule)
    print(f"surface rule fitted on {len(items)} train worlds, {rule['train_claims']} claims; "
          f"base rates {rule['base_rates']}; sha256 {rule['sha256'][:12]}")
    return rule


def tasks_doc(out: str = "docs/SPRINT_TASKS.md") -> None:
    """The exact task statement, vocabulary and follow-up templates, rendered from the code (with hashes)."""
    from . import tasks as T
    m = json.loads((ART / "sprint_smoke_manifest.json").read_text())
    x = m["items"][0]
    pub = P.evaluator(P.WorldKey.from_json(x)).public()
    h = T.template_hashes()
    L = ["# Sprint tasks (exact text; generated by `python -m causalguard sprint-build tasks-doc`)", "",
         f"Task version `{T.TASK_VERSION}`. Pre-sprint work (R7). Hashes are sha256 of the exact template strings.", "",
         "## Task S (turn 1)", "", f"System message (sha256 `{h['system'][:16]}`):", "", "```", T.system(), "```", "",
         f"User message = the rendered public task, a blank line, the instructions (sha256 "
         f"`{h['task_s_instructions'][:16]}`) and the reply format (sha256 `{h['answer_format'][:16]}`). Example "
         f"(smoke world `{x['wkey']}`, never part of the pilot or main panel):", "", "```", T.user_prompt(pub), "```", "",
         "Verdict vocabulary: `true` = settled true (entailed: holds in every consistent mechanism), `false` = "
         "settled false (refuted), `not settled` = some consistent mechanisms make the claim true and others false. "
         "Probability: P(claim true | evidence) under the uniform prior over distinct mechanisms in the class; the "
         "unique correct value is p* = (consistent mechanisms making it true) / (consistent mechanisms).", "",
         "## Task P (turn 2): follow-up templates", "",
         "`{named}` = the named claim ids (4 of 8, by hash), joined as `c1, c3, c4 and c6`. `{checker}` = one line "
         "per named claim, computed from the public evidence only (see the P3 example below).", "",
         "| condition | wording | template | sha256 |", "|---|---|---|---|"]
    for (c, w), t in sorted(T.FOLLOWUPS.items()):
        L.append(f"| {c} | {w} | {t.replace(chr(10), ' / ').replace('|', '/')} | `{h[f'{c}w{w}'][:16]}` |")
    L += ["", "P3 example on the same smoke world, named claims " + ", ".join(x["named"]) + ":", "", "```",
          T.followup(pub, "P3", 1, x["named"]), "```", ""]
    (P.REPO / out).write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="causalguard sprint-build")
    ap.add_argument("step", choices=("manifests", "surface", "engines", "tasks-doc"))
    ap.add_argument("--split", default="main")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    if a.step == "manifests":
        manifests()
    elif a.step == "surface":
        fit_surface()
    elif a.step == "tasks-doc":
        tasks_doc()
    else:
        r = engines(a.split)
        if a.out:
            write_json(Path(a.out), r)
        return 0 if r["worlds_fail"] == 0 and r["worlds_agree"] > 0 else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
