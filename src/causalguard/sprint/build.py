"""R7 sprint build steps (no model calls): manifests, the surface rule fit, and the engine-agreement check.

  python -m causalguard sprint-build manifests            -> artifacts/sprint_{smoke,pilot,main}_manifest.json
  python -m causalguard sprint-build surface              -> artifacts/sprint_surface_rule.json (train split only)
  python -m causalguard sprint-build engines --split S    -> exact engine agreement on every claim of a split
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from . import population as P
from . import surface

ART = P.REPO / "artifacts"


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=1, sort_keys=True) + "\n")


def manifests(splits=("smoke", "pilot", "main", "pilot2", "pilot3")) -> dict:
    out = {}
    for s in splits:
        m = P.manifest(s)
        write_json(ART / f"sprint_{s}_manifest.json", m)
        out[s] = m
        cond = Counter(x["condition"] for x in m["items"])
        print(f"manifest {s}: {m['n_worlds']} worlds, conditions {dict(sorted(cond.items()))}")
    return out


def engines(split: str, quiet: bool = True) -> dict:
    """Every claim of every world of the split through ``Evaluator.reference`` (explicit = D counts and the SAT
    verdict); an exception on any claim is a failed item.  Prints the denominator."""
    keys = P.world_keys(split)
    if not keys:
        raise SystemExit("engines: empty split")
    ok = fail = claims = 0
    st = Counter()
    failures = []
    for k in keys:
        try:
            ref = P.reference(P.evaluator(k))
            ok += 1
            claims += len(ref)
            st.update(r["status"] for r in ref.values())
        except AssertionError as e:
            fail += 1
            failures.append({"wkey": k.wkey, "error": str(e)[:200]})
    res = {"split": split, "worlds": len(keys), "worlds_agree": ok, "worlds_fail": fail, "claims_agree": claims,
           "status_counts": dict(st), "failures": failures}
    print(f"engines {split}: {ok}/{len(keys)} worlds agree ({claims} claims); status {dict(st)}")
    return res


def fit_surface() -> dict:
    keys = P.world_keys("train")
    items = []
    for k in keys:
        ev = P.evaluator(k)
        items.append((ev.public(), P.reference(ev, crosscheck_sat=False)))
    rule = surface.fit(items)
    write_json(ART / "sprint_surface_rule.json", rule)
    print(f"surface rule fitted on {len(items)} train worlds, {rule['train_claims']} claims; "
          f"base rates {rule['base_rates']}; sha256 {rule['sha256'][:12]}")
    return rule


def tasks_doc(out: str = "docs/SPRINT_TASKS.md") -> None:
    """The exact task statement for both tiers, the five follow-up conditions and one P3 and one P4 example per
    tier, rendered from the code (with template hashes).  Examples come from pilot-4 worlds (never main panel)."""
    from . import tasks as T
    from . import tierw as TW
    m = json.loads((ART / "sprint_pilot4_manifest.json").read_text())
    salt = m["assign_salt"]
    xw = min((x for x in m["items"] if x["tier"] == "W" and len(x["named"]) == 4),
             key=lambda x: __import__("hashlib").sha256(f"r7b-doc|{x['wkey']}".encode()).hexdigest())
    xh = min((x for x in m["items"] if x["tier"] == "H"),
             key=lambda x: __import__("hashlib").sha256(f"r7b-doc|{x['wkey']}".encode()).hexdigest())
    _, pw = P.tier_public(P.WorldKey.from_json(xw), "W")
    _, ph = P.tier_public(P.WorldKey.from_json(xh), "H")
    h = T.template_hashes()
    L = ["# Sprint tasks (exact text; generated by `python -m causalguard sprint-build tasks-doc`)", "",
         f"Task version `{T.TASK_VERSION}`. Pre-sprint work (R7b). Hashes are sha256 of the exact template strings.",
         "", "Two tiers share the evidence and claim design, the instructions, the reply format and the follow-ups:", "",
         "- **Tier W (wiring given, primary).** The prompt lists each node's input nodes. A node's next value is "
         "settled exactly when its input combination at that state appears in an evidence row where it was not "
         "clamped, so every status can be derived by table lookup.",
         "- **Tier H (wiring hidden, contrast).** Each node is an unknown function of at most three of the eight "
         "nodes; working out a status means reasoning over every such function that fits the rows.", "",
         "## Task S (turn 1)", "", f"System message (sha256 `{h['system'][:16]}`):", "", "```", T.system(), "```", "",
         f"User message = the rendered public task, a blank line, the instructions (sha256 "
         f"`{h['task_s_instructions'][:16]}`), the reasoning-first reply instruction (sha256 "
         f"`{h['reply_instruction_v3'][:16]}`) and the reply format (sha256 `{h['answer_format'][:16]}`).", "",
         f"### Tier W example (pilot-4 world `{xw['wkey']}`, never part of the main panel)", "",
         "```", T.user_prompt(pw), "```", "",
         f"### Tier H example (pilot-4 world `{xh['wkey']}`)", "", "```", T.user_prompt(ph), "```", "",
         "Verdict vocabulary: `true` = settled true (holds in every consistent mechanism), `false` = settled false, "
         "`not settled` = some consistent mechanisms make the claim true and others false. Probability: P(claim true "
         "| evidence) under the uniform prior over distinct mechanisms of the tier's class.", "",
         "## Task P (turn 2): five conditions", "",
         "`{named}` = the named claim ids (up to 4, by hash among claims whose derivation fits the cap), joined as "
         "`c1, c3, c4 and c6`. `{checker}` = one block per named claim computed from the public task only: P3 the "
         "valid check, P4 the forged check. **P3 and P4 use the same template.**", "",
         "| tier | condition | wording | template | sha256 |", "|---|---|---|---|---|"]
    for tier, tmpl in (("H", T.FOLLOWUPS), ("W", T.FOLLOWUPS_W)):
        for (c, w), t in sorted(tmpl.items()):
            key = f"{c}w{w}" if tier == "H" else f"W{c}w{w}"
            L.append(f"| {tier} | {c} | {w} | {t.replace(chr(10), ' / ').replace('|', '/')} | `{h[key][:16]}` |")
    L += ["", "On Tier W a check can be verified by looking up the rows it cites; the forged check contains one "
          "statement the evidence contradicts (a row cited for inputs it does not show, a wrong value for a cited "
          "row, or 'no evidence row shows these inputs' where one does) and is otherwise coherent. On Tier H neither "
          "the valid nor the forged check can be verified by lookup.", ""]
    for tier, x, pub in (("W", xw, pw), ("H", xh, ph)):
        for cond in ("P3", "P4"):
            L += [f"### Tier {tier}, {cond} example (named {', '.join(x['named'])}; true statuses "
                  + ", ".join(f"{c} {x['checker_status'][c]}" for c in x["named"]) + ")", "", "```",
                  T.followup(pub, cond, 1, x["named"], salt), "```", ""]
        if tier == "W":
            probs = {c: TW.verify(pub, c, *(lambda pk: (pk["forged"]["tree"], pk["forged"]["status"],
                                                        pk["forged"]["lines"]))(TW.claim_package(pub, c, salt)))
                     for c in x["named"]}
            L += ["What the verifier finds in the P4 example (the false statement per claim):", ""]
            L += [f"- {c} ({x['forgery_kind'][c]}): {'; '.join(v)}" for c, v in probs.items()] + [""]
    L += p5_tasks_section()
    (P.REPO / out).write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


def _p5_example_items() -> tuple:
    """One P5v and one P5f example from the P5 manifest by sha256('r7b-p5-doc', wkey) (worlds with 4 named)."""
    import hashlib as _hl
    m = json.loads((ART / "sprint_p5_manifest.json").read_text())
    pick = {}
    for cond in ("P5v", "P5f"):
        pick[cond] = min((x for x in m["items"] if x["condition"] == cond and len(x["named"]) == 4),
                         key=lambda x: _hl.sha256(f"r7b-p5-doc|{x['wkey']}".encode()).hexdigest())
    return m, pick


def _p5_worked(pub: dict, cid: str, salt: str, f: dict) -> list[str]:
    """SPRINT (lock v2): the same claim under P5f (wording 1, this claim named alone) and how the P5 scorer reads
    three possible replies."""
    from . import scoring as S
    from . import tasks as T
    from . import tierw as TW
    a = TW.altered_lines(pub, cid, salt)
    msg = T.followup(pub, "P5f", 1, [cid], salt)
    where = f"row #{a['row']:02d}" if a["row"] is not None else "no evidence row"
    replies = [("the altered line, quoted", a["lines"][0].strip()),
               ("names the row and the node only", f"{where} does not support what is said about {a['node']}"),
               ("a correct line of the same check", next(ln.strip() for ln in f["lines"][1:]
                                                       if ln not in a["lines"] and "reads" in ln))]
    L = ["## P5 (verify-first) on the same claim (SPRINT, lock v2)", "",
         "The P5f message for this claim alone (wording 1). P5v shows the valid check above inside the same "
         "template.", "", "```", msg, "```", "",
         f"The altered line (forgery kind `{a['kind']}`): `{a['lines'][0].strip()}`", "",
         "How the scorer reads three possible `check_errors` entries for this claim:", "",
         "| entry quoted | exact | lenient |", "|---|---|---|"]
    for name, q in replies:
        r = S.p5_detection_world("P5f", [cid], [{"cid": cid, "line": q}], {cid: a})
        L.append(f"| {name}: `{q}` | {r['exact']:.0f} | {r['lenient']:.0f} |")
    return L + [""]


def p5_tasks_section() -> list[str]:
    """SPRINT (lock v2): the P5 templates and one P5v and one P5f message.  NOTE: these two P5 worlds are shown in
    this document, which no model reads; they remain in the P5 panel (disclosed)."""
    from . import tasks as T
    from . import tierw as TW
    m, pick = _p5_example_items()
    h = T.p5_template_hashes()
    L = ["## P5 verify-first (SPRINT, lock addendum v2; Tier W only)", "",
         "The P3/P4 Tier W template of the same wording with one verification block inserted before the reply "
         "instruction and the reply schema extended by `check_errors`; identical in P5v (valid check) and P5f (forged "
         f"check). Turn 1 is the Tier W Task S message (same suffix sha256 `{T.turn1_suffix_sha256()[:16]}`).", "",
         f"Verification block (sha256 `{h['p5_verify_block'][:16]}`):", "", "> " + T.P5_VERIFY, "",
         f"Schema sentence (sha256 `{h['p5_schema'][:16]}`):", "", "> " + T.P5_SCHEMA, "",
         "| condition | wording | sha256 |", "|---|---|---|"]
    L += [f"| {c} | {w} | `{h[f'W{c}w{w}'][:16]}` |" for (c, w) in sorted(T.FOLLOWUPS_P5)]
    L += [""]
    for cond in ("P5v", "P5f"):
        x = pick[cond]
        _, pub = P.tier_public(P.WorldKey.from_json(x), "W", x["design_salt"])
        L += [f"### {cond} example (P5 world `{x['wkey']}`, wording {x['wording']}; named "
              f"{', '.join(x['named'])})", "", "```", T.followup(pub, cond, x["wording"], x["named"], m["assign_salt"]),
              "```", ""]
        if cond == "P5f":
            L += ["The altered line of each named claim (what an exact detection quotes):", ""]
            for c in x["named"]:
                a = TW.altered_lines(pub, c, m["assign_salt"])
                L += [f"- {c} ({a['kind']}): `{a['lines'][0].strip()}`"]
            L += [""]
    return L


def manifests_r7b(splits=("pilot4", "main")) -> dict:
    """R7b manifests (D79): tier per world, five conditions, named claims among eligible ones, checker and forged
    status of every named claim.  Pilot 4: Tier H worlds are P4 only.  The R7 main manifest (a draft, never run)
    is kept as artifacts/r7_draft/sprint_main_manifest.json."""
    out = {}
    for s in splits:
        if s == "main":
            m = P.manifest_r7b("main", P.MAIN_TIER_COUNTS)
        else:
            m = P.manifest_r7b(s, P.PILOT4_TIER_COUNTS, fixed={"H": "P4"})
        write_json(ART / f"sprint_{s}_manifest.json", m)
        out[s] = m
        cond = Counter((x["tier"], x["condition"]) for x in m["items"])
        print(f"manifest {s}: {m['n_worlds']} worlds, tier x condition {dict(sorted(cond.items()))}; "
              f"named per world {dict(Counter(len(x['named']) for x in m['items']))}")
    return out


def engines_r7b(manifest: str, sat: bool = True) -> dict:
    """G1 on an R7b manifest: every claim of every world through its tier's reference (Tier W: lazy = restricted
    explicit engine = SAT on the Tier W encoding; Tier H: explicit = D = SAT), and the cross-tier test on every
    world, on its own evidence (Tier H reference vs Tier W reference with the hidden wiring listed: settled on
    Tier H => settled the same way on Tier W)."""
    from . import tierw as TW
    m = json.loads((P.REPO / manifest).read_text())
    if not m["items"]:
        raise SystemExit("engines: empty manifest")
    res = {"manifest": manifest, "worlds": 0, "worlds_agree": 0, "claims": 0, "failures": [],
           "cross_tier_worlds": 0, "cross_tier_claims_settled_h": 0, "cross_tier_violations": [],
           "status_counts": {"W": Counter(), "H": Counter()}}
    for x in m["items"]:
        k = P.WorldKey.from_json(x)
        res["worlds"] += 1
        try:
            ev, pub = P.tier_public(k, x["tier"], x.get("design_salt"))
            ref = P.tier_reference(ev, pub, x["tier"], crosscheck_sat=sat)
            res["worlds_agree"] += 1
            res["claims"] += len(ref)
            res["status_counts"][x["tier"]].update(r["status"] for r in ref.values())
            # cross-tier on the world's own evidence: Tier W evidence (small budget) and Tier H evidence (larger
            # budget, where Tier H settles claims), each with the hidden wiring listed
            if x["tier"] == "W":
                ref_h, ref_w = P.reference(ev, crosscheck_sat=False), ref
            else:
                ref_h = ref
                ref_w = TW.reference_w({**pub, "wiring": TW.wiring_of(ev.world.net), "tier": "W"}, ev.world.net,
                                       sat=sat)
            res["cross_tier_worlds"] += 1
            res["cross_tier_claims_settled_h"] += sum(r["status"] != TW.UND for r in ref_h.values())
            v = TW.cross_tier(ref_h, ref_w)
            if v:
                res["cross_tier_violations"].append({"wkey": x["wkey"], "claims": v})
        except AssertionError as e:
            res["failures"].append({"wkey": x["wkey"], "error": str(e)[:200]})
    res["status_counts"] = {t: dict(c) for t, c in res["status_counts"].items()}
    res["pass"] = not res["failures"] and not res["cross_tier_violations"] and res["worlds_agree"] == res["worlds"]
    print(f"engines {manifest}: {res['worlds_agree']}/{res['worlds']} worlds agree ({res['claims']} claims); "
          f"cross-tier {res['cross_tier_worlds']} worlds, {res['cross_tier_claims_settled_h']} claims settled on H, "
          f"{len(res['cross_tier_violations'])} violations; status {res['status_counts']}")
    return res


def calibrate_w(budgets_grid=((4,), (6,), (8,), (10,), (6, 8)), chosen=(6, 8)) -> dict:
    """Tier W evidence-budget calibration on the TRAIN split (no model): status shares overall and by horizon,
    named-claim eligibility and derivation length per budget set; the two Tier W implementations must agree on
    every item (SAT too for the chosen set).  Then fits the Tier W surface rule on the chosen set.  Writes
    artifacts/r7b_tierw_calibration.json and artifacts/sprint_surface_rule_w.json."""
    import hashlib as _hl

    from . import tierw as TW
    keys = P.world_keys("train")
    out = {"split": "train", "worlds": len(keys), "grid": {}, "chosen": list(chosen)}
    items = []
    for bs in budgets_grid:
        st, byh, lens, elig, nclaims, fail = Counter(), Counter(), [], 0, 0, 0
        named_ok = 0
        for k in keys:
            ev = P.evaluator_w(k, budgets=bs)
            pub = P.public_w(ev)
            try:
                ref = TW.reference_w(pub, ev.world.net, sat=(tuple(bs) == tuple(chosen)))
            except AssertionError:
                fail += 1
                continue
            tab = TW.Table.from_public(pub)
            ne = 0
            for c, r in ref.items():
                st[r["status"]] += 1
                byh[f"h{r['h']}|{'open' if r['status'] == TW.UND else 'settled'}"] += 1
                pk = TW.claim_package(pub, c, "r7b-calibration", tab)
                lens.append(pk["n_lines"])
                elig += pk["eligible"]
                ne += pk["eligible"]
                nclaims += 1
            named_ok += ne >= P.N_NAMED
            if tuple(bs) == tuple(chosen):
                items.append((pub, ref))
        lens.sort()
        out["grid"]["+".join(map(str, bs))] = {
            "claims": nclaims, "engine_failures": fail,
            "status_share": {s_: round(v / nclaims, 4) for s_, v in sorted(st.items())},
            "by_horizon": dict(sorted(byh.items())), "eligible_share": round(elig / nclaims, 4),
            "worlds_with_4_eligible": named_ok, "derivation_lines_median": lens[len(lens) // 2],
            "derivation_lines_p90": lens[int(0.9 * (len(lens) - 1))], "derivation_lines_max": lens[-1]}
        g = out["grid"]["+".join(map(str, bs))]
        print(f"budgets {bs}: {g['status_share']} eligible {g['eligible_share']} failures {fail}")
    rule = surface.fit(items)
    rule["tier"] = "W"
    rule["sha256"] = _hl.sha256(json.dumps({k: v for k, v in rule.items() if k != "sha256"},
                                           sort_keys=True).encode()).hexdigest()
    write_json(ART / "sprint_surface_rule_w.json", rule)
    out["surface_rule_w_sha256"] = rule["sha256"]
    write_json(ART / "r7b_tierw_calibration.json", out)
    return out


def worked_example_doc(out: str = "reports/R7B_WORKED_EXAMPLE.md") -> None:
    """One Tier W claim a reader can verify from the page, with its valid (P3) and forged (P4) check.  Chosen from
    pilot-4 worlds (never main panel) by a fixed rule on the PUBLIC task: a not-settled claim whose valid
    derivation has a case split and at most 9 lines, then the smallest sha256('r7b-worked', wkey, cid)."""
    import hashlib as _hl

    from ..s4.pilot import render_claim
    from . import tasks as T
    from . import tierw as TW
    m = json.loads((ART / "sprint_pilot4_manifest.json").read_text())
    salt = m["assign_salt"]
    best = None
    for x in m["items"]:
        if x["tier"] != "W":
            continue
        _, pub = P.tier_public(P.WorldKey.from_json(x), "W")
        tab = TW.Table.from_public(pub)
        for c in pub["claims"]:
            pk = TW.claim_package(pub, c["cid"], salt, tab)
            if pk["status"] == TW.UND and pk["eligible"] and pk["tree"]["cases"] is not None and pk["n_lines"] <= 9:
                key = _hl.sha256(f"r7b-worked|{x['wkey']}|{c['cid']}".encode()).hexdigest()
                if best is None or key < best[0]:
                    best = (key, x, pub, c, pk)
    _, x, pub, c, pk = best
    f = pk["forged"]
    lines = T.user_prompt(pub).split("\n")
    task = "\n".join(lines[:lines.index("Claims:")])
    bad = TW.verify(pub, c["cid"], f["tree"], f["status"], f["lines"])
    L = ["# R7b worked example (Tier W, pre-sprint)", "",
         f"Generated by `python -m causalguard sprint-build worked-example` from pilot-4 world `{x['wkey']}` (never "
         "part of the main panel). Selection rule, fixed before looking: a not-settled claim whose valid derivation "
         "has a case split and at most 9 lines; among those the smallest sha256('r7b-worked', world, claim).", "",
         "## The public task (evidence and wiring)", "", "```", task, "```", "",
         "## The claim", "", "```", render_claim(c, pub), "```", "",
         f"Exact status: **{ {'entailed': 'true', 'refuted': 'false', 'underdetermined': 'not settled'}[pk['status']] }**, "
         f"probability {pk['p_star']} (fraction of the ways to fill the unobserved table entries that make it true).",
         "", "## The valid check (what P3 shows)", "", "```", *pk["lines"], "```", "",
         "How to verify it by hand: for each line, find the cited row, read the listed input nodes in that row's "
         "start state (for a clamped row the clamped values are already written into the start state) and the "
         "node's next value after the arrow. A line that says no row shows the inputs is checked by scanning the "
         "rows for that input combination with the node not clamped. Each case then follows the same way.", "",
         f"## The forged check (what P4 shows; forgery kind `{f['kind']}`)", "", "```", *f["lines"], "```", "",
         "What the verifier finds (one false statement; everything else in the forged check is consistent):", "",
         *[f"- {b}" for b in bad], ""]
    L += _p5_worked(pub, c["cid"], salt, f)
    (P.REPO / out).write_text("\n".join(L) + "\n")
    print(f"wrote {out}: {x['wkey']} {c['cid']}")


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="causalguard sprint-build")
    ap.add_argument("step", choices=("manifests", "surface", "engines", "tasks-doc", "r7b-manifests", "r7b-engines",
                                         "r7b-calibrate", "worked-example"))
    ap.add_argument("--manifest", default="artifacts/sprint_main_manifest.json")
    ap.add_argument("--split", default="main")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    if a.step == "manifests":
        manifests()
    elif a.step == "worked-example":
        worked_example_doc()
    elif a.step == "r7b-calibrate":
        calibrate_w()
    elif a.step == "r7b-manifests":
        manifests_r7b()
    elif a.step == "r7b-engines":
        r = engines_r7b(a.manifest)
        if a.out:
            write_json(Path(a.out), r)
        return 0 if r["pass"] else 1
    elif a.step == "surface":
        fit_surface()
    elif a.step == "tasks-doc":
        tasks_doc()
    else:
        r = engines(a.split)
        if a.out:
            write_json(Path(a.out), r)
        return 0 if r["worlds_fail"] == 0 and r["worlds_agree"] > 0 else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
